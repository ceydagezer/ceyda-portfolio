/* LANGUAGE */
/* ========================= */

function applyLanguage(language) {

  const dictionary =
    translations[language] ||
    translations.en


  document
    .querySelectorAll("[data-i18n]")
    .forEach((element) => {

      const key =
        element.dataset.i18n

      if (dictionary[key]) {
        element.textContent =
          dictionary[key]
      }

    })


  document
    .querySelectorAll(
      "[data-i18n-placeholder]"
    )
    .forEach((element) => {

      const key =
        element.dataset.i18nPlaceholder

      if (dictionary[key]) {
        element.placeholder =
          dictionary[key]
      }

    })


  document
    .querySelectorAll(".lang-button")
    .forEach((button) => {

      button.classList.toggle(
        "active",
        button.dataset.lang === language
      )

    })


  document.documentElement.lang =
    language


  localStorage.setItem(
    "portfolioLanguage",
    language
  )
}


/* LANGUAGE BUTTON EVENTS */

document
  .querySelectorAll(".lang-button")
  .forEach((button) => {

    button.addEventListener(
      "click",
      () => {

        applyLanguage(
          button.dataset.lang
        )

      }
    )

  })


/* LOAD SAVED LANGUAGE */

const savedLanguage =
  localStorage.getItem(
    "portfolioLanguage"
  ) || "en"


applyLanguage(savedLanguage)


